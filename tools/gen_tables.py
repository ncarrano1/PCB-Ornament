#!/usr/bin/env python3
"""Generate src/tables.c: const lookup tables for the ornament firmware.

The Cortex-M3 has no FPU, so all curves are precomputed here.
Run from the repo root:  python3 tools/gen_tables.py
"""
import math

GAMMA = 2.2


def fmt(name, ctype, values, per_line=12):
    lines = [f"const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


# Perceptual brightness 0..255 -> linear light 0..65535.
gamma = [round(65535 * (i / 255) ** GAMMA) for i in range(256)]
# Linear weight 0..255 -> perceptual 0..255 (inverse gamma), used to split a
# point between two LEDs without the brightness dipping between them.
inv_gamma = [round(255 * (i / 255) ** (1 / GAMMA)) for i in range(256)]
# One full sine period, Q15.
sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
# exp(-x) for x = i/32, i.e. 0..8 e-folds, scaled to 0..65535.
exp_neg = [round(65535 * math.exp(-i / 32)) for i in range(256)]

out = [
    "/*",
    " * tables.c - GENERATED by tools/gen_tables.py. Do not edit by hand.",
    " */",
    '#include "tables.h"',
    "",
    f"/* Perceptual 0..255 -> linear 0..65535, gamma {GAMMA}. */",
    fmt("TBL_GAMMA", "uint16_t", gamma, 10),
    "",
    "/* Linear weight 0..255 -> perceptual 0..255 (inverse gamma). */",
    fmt("TBL_INV_GAMMA", "uint8_t", inv_gamma, 16),
    "",
    "/* sin(2*pi*i/256), Q15. */",
    fmt("TBL_SINE", "int16_t", sine, 12),
    "",
    "/* exp(-i/32) * 65535. */",
    fmt("TBL_EXP_NEG", "uint16_t", exp_neg, 10),
    "",
]
with open("src/tables.c", "w") as f:
    f.write("\n".join(out))
print("wrote src/tables.c")
